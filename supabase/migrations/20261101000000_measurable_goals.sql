  ) then
    alter table public.milestones
      add constraint milestones_target_value_non_negative
      check (target_value is null or target_value >= 0);
  end if;
end
$$;

-- Aportes reales. El progreso se calcula sumando esta tabla.
create table if not exists public.progress_entries (
  id bigint generated by default as identity primary key,
  goal_id bigint not null references public.goals(id) on delete cascade,
  milestone_id bigint references public.milestones(id) on delete set null,
  amount numeric(14, 2) not null,
  entry_date date not null default current_date,
  note text,
  created_at timestamptz not null default now()
);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'progress_entries_amount_positive'
      and conrelid = 'public.progress_entries'::regclass
  ) then
    alter table public.progress_entries
      add constraint progress_entries_amount_positive
      check (amount > 0);
  end if;
end
$$;

