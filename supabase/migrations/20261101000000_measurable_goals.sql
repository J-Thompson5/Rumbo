  on public.milestones (goal_id, period_start);

-- Un aporte con milestone_id debe pertenecer a la misma meta.
create or replace function public.validate_progress_entry_milestone()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.milestone_id is not null then
    if not exists (
      select 1
      from public.milestones m
      where m.id = new.milestone_id
        and m.goal_id = new.goal_id
    ) then
      raise exception 'El hito % no pertenece a la meta %.', new.milestone_id, new.goal_id
        using errcode = '23514';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists validate_progress_entry_milestone on public.progress_entries;
create trigger validate_progress_entry_milestone
before insert or update on public.progress_entries
for each row execute function public.validate_progress_entry_milestone();

-- ============================================================================
-- 2. Vistas de progreso
-- ============================================================================
-- Se crean vistas nuevas para no reemplazar goals_progress / milestones_progress
-- (no conocemos su definición exacta y no queremos romper consumidores actuales).
-- security_invoker hace que las RLS de las tablas base sigan aplicando.
-- ============================================================================

create or replace view public.goals_overview as
with task_stats as (
  select
    m.goal_id,
    count(t.id)::int as total_tasks,
    (count(t.id) filter (where t.is_completed))::int as done_tasks
  from public.milestones m
  left join public.tasks t on t.milestone_id = m.id
  group by m.goal_id
),
contribution_stats as (
  select
    pe.goal_id,
    coalesce(sum(pe.amount), 0)::numeric as total_contributed
  from public.progress_entries pe
  group by pe.goal_id
)
select
  g.id,
  g.user_id,
  g.title,
  g.description,
  g.deadline,
  g.created_at,
  g.target_value,
  g.unit,
  g.start_date,
  coalesce(ts.total_tasks, 0) as total_tasks,
  coalesce(ts.done_tasks, 0) as done_tasks,
  coalesce(cs.total_contributed, 0) as total_contributed,
  case
    when g.target_value is not null and g.target_value > 0 then
      least(100, round(coalesce(cs.total_contributed, 0) / g.target_value * 100, 2))
    when coalesce(ts.total_tasks, 0) > 0 then
      round(coalesce(ts.done_tasks, 0)::numeric / ts.total_tasks * 100, 2)
    else 0
  end as progress_percentage,
  case
    when g.target_value is not null then 'amount'
    else 'tasks'
  end as progress_mode,
  case
    when g.target_value is not null then
      greatest(g.target_value - coalesce(cs.total_contributed, 0), 0)
    else null
  end as remaining_value
from public.goals g
left join task_stats ts on ts.goal_id = g.id
left join contribution_stats cs on cs.goal_id = g.id
where g.user_id = auth.uid();

create or replace view public.milestones_overview as
with task_stats as (
  select
    t.milestone_id,
    count(*)::int as total_tasks,
    (count(*) filter (where t.is_completed))::int as done_tasks
  from public.tasks t
  where t.milestone_id is not null
  group by t.milestone_id
),
entry_stats as (
  select
    m.id as milestone_id,
    coalesce(sum(pe.amount), 0)::numeric as total_contributed
  from public.milestones m
  left join public.progress_entries pe
    on pe.goal_id = m.goal_id
   and pe.entry_date between coalesce(m.period_start, m.start_date::date)
                         and coalesce(m.period_end, m.end_date::date)
  group by m.id
)
select
  m.id,
  m.goal_id,
  m.parent_id,
  m.title,
  m.type,
  m.start_date,
  m.end_date,
  m.created_at,
  m.period_start,
  m.period_end,
  m.target_value,
  m.is_necessary,
  m.closed_at,
  coalesce(ts.total_tasks, 0) as total_tasks,
  coalesce(ts.done_tasks, 0) as done_tasks,
  coalesce(es.total_contributed, 0) as total_contributed,
  case
    when m.target_value is not null and m.target_value > 0 then
      least(100, round(coalesce(es.total_contributed, 0) / m.target_value * 100, 2))
    when m.target_value = 0 then 100
    when m.target_value is null and coalesce(ts.total_tasks, 0) > 0 then
      round(coalesce(ts.done_tasks, 0)::numeric / ts.total_tasks * 100, 2)
    else 0
  end as progress_percentage,
  case
    when m.target_value is not null then
      greatest(m.target_value - coalesce(es.total_contributed, 0), 0)
    else null
  end as remaining_value
from public.milestones m
join public.goals g on g.id = m.goal_id
left join task_stats ts on ts.milestone_id = m.id
left join entry_stats es on es.milestone_id = m.id
where g.user_id = auth.uid();

-- En PostgreSQL 15+ las vistas pueden respetar la RLS del usuario que consulta.
do $$
begin
  if current_setting('server_version_num')::int >= 150000 then
    execute 'alter view public.goals_overview set (security_invoker = true)';
    execute 'alter view public.milestones_overview set (security_invoker = true)';
  end if;
end
$$;

-- ============================================================================
-- 3. Función de generación de hitos (ambos modos)
-- ============================================================================
-- p_mode = 'deadline'      -> usa goals.deadline y reparte (target - aportado)
--                             entre los períodos que caben antes del deadline.
-- p_mode = 'contribution'  -> usa p_contribution como aporte por período y
--                             calcula/actualiza goals.deadline.
-- p_periodicity = 'monthly' | 'weekly'.
-- Es idempotente: si la meta ya tiene hitos con target_value, no duplica.
-- ============================================================================

create or replace function public.generate_goal_milestones(
  p_goal_id bigint,
  p_periodicity text default 'monthly',
  p_mode text default 'deadline',
  p_contribution numeric default null
)
returns setof public.milestones
language plpgsql
security definer
set search_path = public
as $$
declare
  v_goal public.goals%rowtype;
  v_start date;
  v_deadline date;
  v_period_count integer := 0;
  v_base numeric;
  v_total_contributed numeric;
  v_amount numeric;
  v_last_amount numeric;
  v_i integer;
  v_period_start date;
  v_period_end date;
  v_next_start date;
  v_existing integer;
  v_title text;
begin
  if p_periodicity is null or p_periodicity not in ('monthly', 'weekly') then
    raise exception 'Periodicidad inválida. Usa monthly o weekly.'
      using errcode = '22023';
  end if;

  if p_mode is null or p_mode not in ('deadline', 'contribution') then
    raise exception 'Modo inválido. Usa deadline o contribution.'
      using errcode = '22023';
  end if;

  select *
  into v_goal
  from public.goals
  where id = p_goal_id;

  if not found then
    raise exception 'No existe la meta %.', p_goal_id
      using errcode = 'P0002';
  end if;

  -- Defensa extra además de la RLS (la función es security definer).
  if auth.uid() is not null and v_goal.user_id is distinct from auth.uid() then
    raise exception 'No tienes permiso sobre esta meta.'
      using errcode = '42501';
  end if;

  if v_goal.target_value is null or v_goal.target_value <= 0 then
    raise exception 'La meta % no tiene un valor objetivo válido.', p_goal_id
      using errcode = '22023';
  end if;

  select count(*)
  into v_existing
  from public.milestones
  where goal_id = p_goal_id
    and target_value is not null;

  if v_existing > 0 then
    return query
      select *
      from public.milestones
      where goal_id = p_goal_id
      order by period_start nulls last, id;
    return;
  end if;

  v_start := coalesce(v_goal.start_date, current_date);

  if v_goal.start_date is null then
    update public.goals
    set start_date = v_start
    where id = p_goal_id;
  end if;

  select coalesce(sum(pe.amount), 0)
  into v_total_contributed
  from public.progress_entries pe
  where pe.goal_id = p_goal_id;

  v_base := greatest(v_goal.target_value - v_total_contributed, 0);

  if v_base <= 0 then
    raise exception 'La meta % ya está completada.', p_goal_id
      using errcode = '22023';
  end if;

  if p_mode = 'deadline' then
    v_deadline := v_goal.deadline::date;

    if v_deadline is null then
      raise exception 'La meta % no tiene fecha límite para el modo fecha.', p_goal_id
        using errcode = '22023';
    end if;

    if v_deadline <= v_start then
      raise exception 'La fecha límite debe ser posterior a la fecha de inicio.'
        using errcode = '22023';
    end if;

    loop
      v_period_start := case
        when p_periodicity = 'monthly'
          then (v_start + (v_period_count::text || ' months')::interval)::date
        else v_start + (v_period_count * 7)
      end;

      exit when v_period_start >= v_deadline;
      v_period_count := v_period_count + 1;
    end loop;
  else
    if p_contribution is null or p_contribution <= 0 then
      raise exception 'El aporte periódico debe ser mayor que cero.'
        using errcode = '22023';
    end if;

    v_amount := round(p_contribution, 2);

    if v_amount <= 0 then
      raise exception 'El aporte periódico es demasiado pequeño.'
        using errcode = '22023';
    end if;

    v_period_count := ceil(v_base / v_amount)::integer;

    -- Fecha estimada: start_date + ceil(target / aporte) períodos.
    v_deadline := case
      when p_periodicity = 'monthly'
        then (v_start + (v_period_count::text || ' months')::interval - interval '1 day')::date
      else v_start + (v_period_count * 7) - 1
    end;

    update public.goals
    set deadline = v_deadline
    where id = p_goal_id;
  end if;

  if v_period_count <= 0 then
    raise exception 'No se generaron períodos para la meta %.', p_goal_id
      using errcode = '22023';
  end if;

  -- Límite de seguridad para evitar generar millones de hitos por error.
  if v_period_count > 5200 then
    raise exception 'La planificación genera demasiados períodos (%). Ajusta el aporte o la fecha.', v_period_count
      using errcode = '22023';
  end if;

  if p_mode = 'deadline' then
    -- trunc evita que el último período quede negativo por redondeo.
    v_amount := trunc(v_base / v_period_count, 2);
    v_last_amount := v_base - (v_amount * (v_period_count - 1));
  else
    v_last_amount := v_base - (v_amount * (v_period_count - 1));
  end if;

  for v_i in 1..v_period_count loop
    v_period_start := case
      when p_periodicity = 'monthly'
        then (v_start + ((v_i - 1)::text || ' months')::interval)::date
      else v_start + ((v_i - 1) * 7)
    end;

    v_next_start := case
      when p_periodicity = 'monthly'
        then (v_start + (v_i::text || ' months')::interval)::date
      else v_start + (v_i * 7)
    end;

    if v_i = v_period_count then
      v_period_end := v_deadline;
    else
      v_period_end := v_next_start - 1;
    end if;

    v_title := case
      when p_periodicity = 'monthly' then format('Mes %s', v_i)
      else format('Semana %s', v_i)
    end;

    insert into public.milestones (
      goal_id,
      title,
      type,
      start_date,
      end_date,
      period_start,
      period_end,
      target_value,
      is_necessary
    ) values (
      p_goal_id,
      v_title,
      p_periodicity,
      v_period_start,
      v_period_end,
      v_period_start,
      v_period_end,
      case when v_i = v_period_count then v_last_amount else v_amount end,
      true
    );
  end loop;

  return query
    select *
    from public.milestones
    where goal_id = p_goal_id
    order by period_start nulls last, id;
end;
$$;

-- ============================================================================
-- 4. Función de recálculo de hitos futuros (idempotente)
-- ============================================================================
-- Para una meta medible:
--   nuevo target de cada hito futuro =
--       (target_value de la meta - total aportado) / períodos futuros restantes
--
-- No toca:
--   * hitos que ya empezaron o terminaron (period_start <= current_date)
--   * hitos cerrados (closed_at is not null)
--   * hitos marcados como no necesarios
--
-- Si la meta ya se completó, los hitos futuros se marcan is_necessary = false.
-- ============================================================================

create or replace function public.recalculate_goal_milestones(p_goal_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_goal public.goals%rowtype;
  v_total numeric;
  v_remaining numeric;
  v_future_count integer;
  v_per_amount numeric;
  v_last_amount numeric;
  v_i integer := 0;
  r record;
begin
  select *
  into v_goal
  from public.goals
  where id = p_goal_id;

  if not found then
    raise exception 'No existe la meta %.', p_goal_id
      using errcode = 'P0002';
  end if;

  if auth.uid() is not null and v_goal.user_id is distinct from auth.uid() then
    raise exception 'No tienes permiso sobre esta meta.'
      using errcode = '42501';
  end if;

  -- Las metas no medibles conservan el comportamiento actual basado en tareas.
  if v_goal.target_value is null or v_goal.target_value <= 0 then
    return;
  end if;

  select coalesce(sum(pe.amount), 0)
  into v_total
  from public.progress_entries pe
  where pe.goal_id = p_goal_id;

  v_remaining := greatest(v_goal.target_value - v_total, 0);

  if v_remaining <= 0 then
    update public.milestones m
    set is_necessary = false
    where m.goal_id = p_goal_id
      and coalesce(m.period_start, m.start_date::date) > current_date
      and m.closed_at is null
      and m.is_necessary = true;

    return;
  end if;

  -- Si la meta vuelve a tener saldo pendiente (por ejemplo, se eliminó un
  -- aporte), los hitos futuros que se habían marcado como no necesarios
  -- vuelven a ser necesarios. Los cerrados no se tocan.
  update public.milestones m
  set is_necessary = true
  where m.goal_id = p_goal_id
    and coalesce(m.period_start, m.start_date::date) > current_date
    and m.closed_at is null
    and m.is_necessary = false;

  select count(*)
  into v_future_count
  from public.milestones m
  where m.goal_id = p_goal_id
    and coalesce(m.period_start, m.start_date::date) > current_date
    and m.closed_at is null
    and m.is_necessary = true;

  if v_future_count = 0 then
    return;
  end if;

  -- trunc evita que el último período quede negativo por redondeo.
  v_per_amount := trunc(v_remaining / v_future_count, 2);
  v_last_amount := v_remaining - (v_per_amount * (v_future_count - 1));

  for r in
    select m.id
    from public.milestones m
    where m.goal_id = p_goal_id
      and coalesce(m.period_start, m.start_date::date) > current_date
      and m.closed_at is null
      and m.is_necessary = true
    order by coalesce(m.period_start, m.start_date::date), m.id
  loop
    v_i := v_i + 1;

    update public.milestones
    set target_value = case
      when v_i = v_future_count then v_last_amount
      else v_per_amount
    end
    where id = r.id;
  end loop;
end;
$$;

-- ============================================================================
-- 5. RLS para progress_entries
-- ============================================================================
-- Cada usuario solo ve / modifica aportes de metas propias.
-- La pertenencia se deriva de goals.user_id, igual que el resto del modelo.
-- ============================================================================

alter table public.progress_entries enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'progress_entries'
      and policyname = 'progress_entries_select_own'
  ) then
    execute $policy$
      create policy progress_entries_select_own
        on public.progress_entries
        for select
        to authenticated
        using (
          exists (
            select 1
            from public.goals g
            where g.id = progress_entries.goal_id
              and g.user_id = auth.uid()
          )
        )
    $policy$;
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'progress_entries'
      and policyname = 'progress_entries_insert_own'
  ) then
    execute $policy$
      create policy progress_entries_insert_own
        on public.progress_entries
        for insert
        to authenticated
        with check (
          exists (
            select 1
            from public.goals g
            where g.id = progress_entries.goal_id
              and g.user_id = auth.uid()
          )
          and (
            progress_entries.milestone_id is null
            or exists (
              select 1
              from public.milestones m
              where m.id = progress_entries.milestone_id
                and m.goal_id = progress_entries.goal_id
            )
          )
        )
    $policy$;
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'progress_entries'
      and policyname = 'progress_entries_update_own'
  ) then
    execute $policy$
      create policy progress_entries_update_own
        on public.progress_entries
        for update
        to authenticated
        using (
          exists (
            select 1
            from public.goals g
            where g.id = progress_entries.goal_id
              and g.user_id = auth.uid()
          )
        )
        with check (
          exists (
            select 1
            from public.goals g
            where g.id = progress_entries.goal_id
              and g.user_id = auth.uid()
          )
          and (
            progress_entries.milestone_id is null
            or exists (
              select 1
              from public.milestones m
              where m.id = progress_entries.milestone_id
                and m.goal_id = progress_entries.goal_id
            )
          )
        )
    $policy$;
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'progress_entries'
      and policyname = 'progress_entries_delete_own'
  ) then
    execute $policy$
      create policy progress_entries_delete_own
        on public.progress_entries
        for delete
        to authenticated
        using (
          exists (
            select 1
            from public.goals g
            where g.id = progress_entries.goal_id
              and g.user_id = auth.uid()
          )
        )
    $policy$;
  end if;
end
$$;

