-- ============================================================================
-- Fractal · Metas medibles con hitos periódicos
-- ============================================================================
-- Cambios NO destructivos:
--   * Solo se agregan columnas, tabla, vistas, funciones, índices y políticas.
--   * No se renombra ni se elimina nada existente.
--   * Las metas sin target_value siguen usando el progreso por tareas.
--
-- Reglas de negocio implementadas:
--   * El progreso nunca se guarda a mano: se suma desde progress_entries.
--   * Progreso de hito  = aportes del hito / target_value del hito.
--   * Progreso de meta  = todos los aportes / target_value de la meta.
--   * Metas sin target_value = tareas completadas / total de tareas.
--   * Los hitos futuros se recalculan cuando la persona se atrasa o adelanta.
--   * Si la meta se completa antes, los hitos futuros se marcan como
--     no necesarios (is_necessary = false), no se borran.
-- ============================================================================

-- ============================================================================
-- 1. Esquema
-- ============================================================================

alter table public.goals
  add column if not exists target_value numeric(14, 2),
  add column if not exists unit text,
  add column if not exists start_date date;

-- Las metas existentes toman como inicio la fecha en que fueron creadas.
update public.goals
set start_date = created_at::date
where start_date is null
  and created_at is not null;

alter table public.milestones
  add column if not exists period_start date,
  add column if not exists period_end date,
  add column if not exists target_value numeric(14, 2),
  add column if not exists is_necessary boolean not null default true,
  add column if not exists closed_at timestamptz;

-- Los hitos existentes conservan sus fechas actuales como período.
update public.milestones
set period_start = coalesce(period_start, start_date::date),
    period_end   = coalesce(period_end, end_date::date)
where (period_start is null and start_date is not null)
   or (period_end is null and end_date is not null);

-- Restricciones (se agregan solo si no existen, para poder re-ejecutar).
do $$
